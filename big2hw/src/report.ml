(* What was read from the model and what was built from it, as text. *)

let line fmt = Printf.sprintf (fmt ^^ "\n")

let bus name width = if width = 1 then name else Printf.sprintf "%s[%d:0]" name (width - 1)

let machine (m : Design.machine) ~note =
  let width =
    Array.fold_left (fun w (s : Design.state) -> max w (String.length s.name)) 0 m.states
  in
  Array.to_list m.states
  |> List.mapi (fun i (s : Design.state) ->
         let out =
           match s.trans with
           | [] -> "no transition out"
           | ts ->
               String.concat ", "
                 (List.map (fun (label, t) -> Printf.sprintf "--%s--> %s" label m.states.(t).name) ts)
         in
         line "    %d  %-*s  %s%s" i width s.name out
           (match note i with "" -> "" | n -> "    (" ^ n ^ ")"))
  |> String.concat ""

(* The design: symbols, and for each board its machine and its ports. *)
let design (d : Design.t) =
  let w = Hw.sym_width d in
  let tx_w = Hw.state_width d.tx.machine and rx_w = Hw.state_width d.rx.machine in
  let ports l = String.concat ", " l in
  String.concat ""
    [ line "Symbols: what a fibre or a buffer carries, %d bits. 0 is nothing." w;
      String.concat ""
        (List.mapi
           (fun i s ->
             line "    %d  %s%s" (i + 1) s (if List.mem s d.payloads then "    (payload)" else ""))
           d.symbols);
      line "";
      line "Board %s: circuit %s_%s" d.tx.board d.name d.tx.board;
      line "  The transmit machine. State register tx_state, %d bits:" tx_w;
      machine d.tx.machine ~note:(fun _ -> "");
      line "  in   %s" (bus "load" w);
      line "  out  %s"
        (ports
           (List.filter_map (Option.map (fun p -> bus p w)) [ d.tx.ctl; d.tx.dat ]
           @ [ bus "tx_state" tx_w; bus "tx_buf" w ]));
      line "";
      line "Board %s: circuit %s_%s" d.rx.board d.name d.rx.board;
      line "  The channel control. State register cc_state, %d bits:" rx_w;
      machine d.rx.machine ~note:(fun i ->
          if List.mem i d.rx.enable then "drives the gate's enable wire"
          else if i = d.rx.blocked then "the state it fails to"
          else "");
      line "  in   %s"
        (ports
           (List.map
              (fun (i : Design.input) -> bus i.port w ^ if i.gated then " (also to the gate)" else "")
              d.rx.inputs
           @ (if d.rx.hazard then [ "haz_i" ] else [])
           @ [ "rx_take" ]));
      line "  out  %s"
        (ports [ bus "rx_buf" w; bus "cc_state" rx_w; "gate_enable"; bus "dat_held" w; "dat_clash" ]);
      line "";
      line "Fibres, and the whole system as circuit %s:" d.name;
      String.concat "" (List.map (fun (o, i) -> line "    %s -> %s" o i) d.fibres) ]

(* The same, as the comment at the top of a Verilog file. *)
let header ~source (d : Design.t) =
  line "// Generated by big2hw from %s. Do not edit." source
  ^ (String.split_on_char '\n' (design d)
    |> List.map (fun l -> if l = "" then "//\n" else "// " ^ l ^ "\n")
    |> String.concat "")
  ^ "\n"

(* The code of each symbol and each state, by name, for Verilog that is
   written by hand against the circuits: properties, test benches. *)
let codes ~source (d : Design.t) =
  let upper s = String.uppercase_ascii (Design.snake s) in
  let param width name value =
    line "localparam [%d:0] %s = %d'd%d;" (width - 1) name width value
  in
  (* TxIdle of the register tx is TX_IDLE, Idle of cc is CC_IDLE. *)
  let state prefix name =
    let name = upper name in
    let n = String.length prefix in
    if String.length name > n && String.sub name 0 n = prefix then name else prefix ^ name
  in
  let machine prefix (m : Design.machine) =
    Array.to_list m.states
    |> List.mapi (fun i (s : Design.state) -> param (Hw.state_width m) (state prefix s.name) i)
  in
  let w = Hw.sym_width d in
  String.concat ""
    ([ line "// Generated by big2hw from %s. Do not edit." source;
       line "// The code of each symbol, and of each state of each machine.";
       param w "SYM_NONE" 0 ]
    @ List.mapi (fun i s -> param w ("SYM_" ^ upper s) (i + 1)) d.symbols
    @ machine "TX_" d.tx.machine @ machine "CC_" d.rx.machine)

(* A run of the two circuits, one line per clock cycle. *)
let trace (d : Design.t) (cycles : (Sim.step * Sim.seen) list) =
  let get key (seen : Sim.seen) = List.assoc key seen.obs in
  let columns =
    [ ("cycle", fun i _ _ -> string_of_int (i + 1)); ("inputs", fun _ step _ -> Conform.show_step step) ]
    @ List.map
        (fun (i : Design.input) -> (i.port, fun _ _ (seen : Sim.seen) -> List.assoc i.port seen.fibres))
        d.rx.inputs
    @ [ ("enable", fun _ _ (seen : Sim.seen) -> if seen.enable then "1" else "0");
        ("tx", fun _ _ seen -> get "tx" seen);
        ("cc", fun _ _ seen -> get "cc" seen);
        ("rx.buf", fun _ _ seen -> get "rx.buf" seen) ]
    @ if d.sensor then [ ("alarm", fun _ _ seen -> get "alarm" seen) ] else []
  in
  let rows =
    List.map fst columns
    :: List.mapi (fun i (step, seen) -> List.map (fun (_, cell) -> cell i step seen) columns) cycles
  in
  let width k = List.fold_left (fun w row -> max w (String.length (List.nth row k))) 0 rows in
  let widths = List.mapi (fun k _ -> width k) columns in
  String.concat ""
    (List.map
       (fun row ->
         String.concat "  " (List.map2 (fun w cell -> Printf.sprintf "%-*s" w cell) widths row)
         |> String.trim |> line "%s")
       rows)
