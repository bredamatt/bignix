open Big2uppaal

let usage =
  "big2uppaal MODEL.big --worlds NAME,.. [options]\n\
   big2uppaal MODEL.big --system NAME [options]\n\n\
   --worlds: MODEL.big is a system with probabilistic reaction rules (begin\n\
   pbrs). Writes its Markov chain, started from each of the bigraphs named,\n\
   as PREFIX.xml (a UPPAAL-SMC model), with the queries PREFIX.q.\n\n\
   --system: MODEL.big is a compute module in a host site. Writes PREFIX.xml,\n\
   PREFIX.q, PREFIX-reading.q and PREFIX-expect.q. With --report, prints\n\
   what the system is and writes nothing.\n"

let write name text =
  let ch = open_out name in
  output_string ch text;
  close_out ch

(* A system with reaction rules: one Markov chain per initial bigraph. *)
let chains ~file ~worlds ~consts ~max ~steps ~prefix =
  if prefix = "" then raise (Topo.Error "give -o PREFIX");
  let worlds = List.map (fun init -> Chain.load ~consts ~max file ~init) worlds in
  let steps = Emit_chain.steps worlds steps in
  let header =
    [ Printf.sprintf "Generated by big2uppaal from %s. Do not edit." (Filename.basename file) ]
    @ List.map
        (fun (w : Chain.t) ->
          Printf.sprintf "process %s: the system started from %s, %d states, %d transitions"
            w.name w.name w.states (List.length w.trans))
        worlds
    @ [ Printf.sprintf "One reaction takes one time unit. The queries look at %d time units." steps ]
  in
  write (prefix ^ ".xml") (Emit_chain.model ~header worlds);
  write (prefix ^ ".q") (Emit.query_file (Emit_chain.queries ~steps worlds));
  List.iter prerr_endline header

let () =
  let file = ref "" and system = ref "" and level = ref "tray" in
  let prefix = ref "" and sweep = ref None and sets = ref [] and report = ref false in
  let only = ref [] and worlds = ref [] and steps = ref None and max_states = ref 10000 in
  let o = ref Emit.default in
  let pair s =
    match String.index_opt s '=' with
    | Some i -> (String.sub s 0 i, String.sub s (i + 1) (String.length s - i - 1))
    | None -> raise (Arg.Bad (s ^ ": expected NAME=VALUE"))
  in
  let number s = try float_of_string s with Failure _ -> raise (Arg.Bad (s ^ ": not a number")) in
  let spec =
    [ ("--worlds", Arg.String (fun s -> worlds := String.split_on_char ',' s), "NAME,..  the bigraphs to start the reaction rules from");
      ("--steps", Arg.Int (fun v -> steps := Some v), "N  with --worlds: time units the queries look at (default: one more than the longest run)");
      ("--max-states", Arg.Set_int max_states, "N  with --worlds: give up beyond this many states (default 10000)");
      ("--system", Arg.Set_string system, "NAME  the bigraph to read (big NAME = ...)");
      ("--level", Arg.Set_string level, "chip|tray|rack|module  what keeps a state of its own (default tray)");
      ("--set", Arg.String (fun s -> let n, v = pair s in sets := (n, number v) :: !sets), "NAME=V  replace a number declared in the model");
      ("--sweep", Arg.String (fun s -> let n, v = pair s in sweep := Some (n, List.map number (String.split_on_char ',' v))), "NAME=V1,V2,..  one configuration per value");
      ("--horizon", Arg.Float (fun v -> o := { !o with horizon = v }), "S  length of a campaign in seconds (default 300)");
      ("--items", Arg.Int (fun v -> o := { !o with items = v }), "N  most items per worker (default 400)");
      ("--dprime", Arg.Float (fun v -> o := { !o with dprime = v }), "D  largest detectability index allowed (default 1)");
      ("--z", Arg.Float (fun v -> o := { !o with z = v }), "Z  largest single reading, in standard deviations (default 3)");
      ("--runs", Arg.Int (fun v -> o := { !o with runs = v }), "N  runs for the mean queries (default 50)");
      ("--only", Arg.String (fun s -> only := String.split_on_char ',' s), "KIND,..  keep only these instruments: power, thermal, network, telemetry, rf, sound");
      ("-o", Arg.Set_string prefix, "PREFIX  where to write");
      ("--report", Arg.Set report, " describe the system instead of generating a model") ]
  in
  Arg.parse spec (fun s -> file := s) usage;
  try
    if !file = "" || (!system = "" && !worlds = []) then
      raise (Topo.Error "give a model file and --worlds or --system");
    if !system <> "" && !worlds <> [] then raise (Topo.Error "give --worlds or --system, not both");
    if !worlds <> [] then begin
      if !sweep <> None then raise (Topo.Error "--sweep is for --system: use --set with --worlds");
      chains ~file:!file ~worlds:!worlds ~consts:!sets ~max:!max_states ~steps:!steps ~prefix:!prefix;
      exit 0
    end;
    let configs =
      match !sweep with
      | None -> [ ("as declared", []) ]
      | Some (n, vs) -> List.map (fun v -> (Printf.sprintf "%s=%g" n v, [ (n, v) ])) vs
    in
    let topo consts = Topo.of_big (Topo.load ~consts:(consts @ !sets) !file !system) in
    if !report then print_string (Report.text (topo (snd (List.hd configs))))
    else begin
      if !prefix = "" then raise (Topo.Error "give -o PREFIX");
      let lvl = Plant.level_of_string !level in
      let keep (p : Plant.t) =
        if !only = [] then p
        else
          match List.filter (fun (c : Plant.channel) -> List.mem c.kind !only) p.channels with
          | [] -> raise (Topo.Error "--only leaves no instrument")
          | channels -> { p with channels }
      in
      let plants = List.map (fun (_, consts) -> keep (Plant.build ~level:lvl (topo consts))) configs in
      let p = List.hd plants in
      let labels = List.map fst configs in
      let campaign, reading, expect = Emit.queries !o ~labels p in
      let header =
        [ Printf.sprintf "Generated by big2uppaal from %s, system %s, level %s. Do not edit." (Filename.basename !file) !system !level ]
        @ List.mapi (fun j l -> Printf.sprintf "configuration %d: %s" j l) labels
        @ List.mapi (fun c (name, _) -> Printf.sprintf "copy %d: %s" c (if c = 0 then "the actual run" else "differs in the " ^ name)) p.copies
        @ List.mapi (fun ch (c : Plant.channel) -> Printf.sprintf "instrument %d: %s (%s)" ch c.about c.kind) p.channels
      in
      write (!prefix ^ ".xml") (Emit.model !o ~header plants campaign);
      write (!prefix ^ ".q") (Emit.query_file campaign);
      write (!prefix ^ "-reading.q") (Emit.query_file reading);
      write (!prefix ^ "-expect.q") (Emit.query_file expect);
      List.iter prerr_endline header
    end
  with Topo.Error msg ->
    prerr_endline ("big2uppaal: " ^ msg);
    exit 1
